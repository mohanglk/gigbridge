"""PostgreSQL integration tests restricted to the dedicated test database."""

from __future__ import annotations

import io
import os
import re
import subprocess
import sys
import unittest
from unittest.mock import patch
from uuid import uuid4

from sqlalchemy import create_engine, text
from sqlalchemy.engine import URL, make_url
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session


EXPECTED_TEST_DATABASE = "gigbridge_test"
TEST_DATABASE_ENV = "GIGBRIDGE_TEST_DATABASE_URL"
TEST_SCHEMA_PREFIX = "gigbridge_auth_test_"


def _validated_test_database_url(database_url: str | None) -> URL:
    """Require an explicit PostgreSQL URL naming the dedicated test database."""
    if not database_url:
        raise RuntimeError(
            f"Set {TEST_DATABASE_ENV} to the dedicated {EXPECTED_TEST_DATABASE} database."
        )

    try:
        parsed_url = make_url(database_url)
    except (TypeError, ValueError) as exc:
        raise RuntimeError(f"{TEST_DATABASE_ENV} is not a valid database URL.") from exc

    if parsed_url.drivername != "postgresql+psycopg":
        raise RuntimeError(f"{TEST_DATABASE_ENV} must use PostgreSQL with psycopg.")
    if parsed_url.database != EXPECTED_TEST_DATABASE:
        raise RuntimeError(
            f"Refusing integration tests: database must be exactly {EXPECTED_TEST_DATABASE}."
        )
    return parsed_url


def _drop_owned_test_schema(engine, schema_name: str) -> None:
    """Drop only a generated schema owned by these tests, never public or app tables."""
    pattern = rf"{re.escape(TEST_SCHEMA_PREFIX)}[0-9a-f]{{32}}"
    if re.fullmatch(pattern, schema_name) is None:
        raise RuntimeError("Refusing to drop a schema not generated by these tests.")

    quoted_schema = engine.dialect.identifier_preparer.quote(schema_name)
    with engine.begin() as connection:
        connection.execute(text(f"DROP SCHEMA IF EXISTS {quoted_schema} CASCADE"))


def _create_test_schema_and_register_cleanup(test_case_class, engine) -> str:
    """Create an isolated schema and register its cleanup immediately."""
    schema_name = f"{TEST_SCHEMA_PREFIX}{uuid4().hex}"
    quoted_schema = engine.dialect.identifier_preparer.quote(schema_name)
    with engine.begin() as connection:
        connection.execute(text(f"CREATE SCHEMA {quoted_schema}"))

    # addClassCleanup also runs when setUpClass raises after this point.
    test_case_class.addClassCleanup(_drop_owned_test_schema, engine, schema_name)
    return schema_name


class TestDatabaseSafetyUnitTests(unittest.TestCase):
    def test_exact_dedicated_test_database_is_accepted(self) -> None:
        url = _validated_test_database_url(
            "postgresql+psycopg://user:password@localhost:5432/gigbridge_test"
        )

        self.assertEqual(url.database, EXPECTED_TEST_DATABASE)

    def test_application_database_is_rejected(self) -> None:
        with self.assertRaises(RuntimeError):
            _validated_test_database_url(
                "postgresql+psycopg://user:password@localhost:5432/gigbridge"
            )

    def test_unexpected_database_name_is_rejected(self) -> None:
        with self.assertRaises(RuntimeError):
            _validated_test_database_url(
                "postgresql+psycopg://user:password@localhost:5432/gigbridge_test_copy"
            )

    def test_missing_test_url_does_not_fall_back_to_application_url(self) -> None:
        with patch.dict(
            os.environ,
            {"DATABASE_URL": "postgresql+psycopg://user:password@localhost/gigbridge"},
        ):
            os.environ.pop(TEST_DATABASE_ENV, None)
            with self.assertRaises(RuntimeError):
                _validated_test_database_url(os.environ.get(TEST_DATABASE_ENV))


class AuthenticationPostgresIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        base_url = _validated_test_database_url(os.environ.get(TEST_DATABASE_ENV))
        cls.schema = None
        cls.admin_engine = create_engine(base_url)
        cls.addClassCleanup(cls.admin_engine.dispose)
        cls.schema = _create_test_schema_and_register_cleanup(cls, cls.admin_engine)

        scoped_url = base_url.update_query_dict(
            {"options": f"-csearch_path={cls.schema}"}
        )
        cls.database_url = scoped_url.render_as_string(hide_password=False)
        cls.engine = create_engine(scoped_url)
        cls.addClassCleanup(cls.engine.dispose)
        cls.backend_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

        cls._run_migration("6caf9f38df6e")
        with cls.engine.begin() as connection:
            connection.execute(
                text(
                    "INSERT INTO musician_profiles "
                    "(display_name, city, genres, instruments, years_experience, band_status) "
                    "VALUES ('Existing Profile', 'Pune', 'Jazz', 'Guitar', 8, 'solo')"
                )
            )
        cls._run_migration("head")

    @classmethod
    def _run_migration(cls, revision: str) -> None:
        environment = os.environ.copy()
        environment["DATABASE_URL"] = cls.database_url
        command = [
            sys.executable,
            "-m",
            "alembic",
            "-c",
            "alembic.ini",
            "upgrade",
            revision,
        ]
        subprocess.run(
            command,
            cwd=cls.backend_dir,
            env=environment,
            check=True,
            capture_output=True,
            text=True,
        )

    def test_normalized_email_uniqueness_is_enforced_by_postgres(self) -> None:
        from app.modules.auth.models import User

        with Session(self.engine) as session:
            session.add(User(email="  Member@Example.com ", password_hash="hash"))
            session.commit()
            session.add(User(email="member@example.COM", password_hash="hash"))
            with self.assertRaises(IntegrityError):
                session.commit()
            session.rollback()

    def test_role_assignment_foreign_keys_are_enforced_by_postgres(self) -> None:
        from app.modules.auth.models import User, UserPlatformRole

        with Session(self.engine) as session:
            session.add(UserPlatformRole(user_id=uuid4(), role_key="member"))
            with self.assertRaises(IntegrityError):
                session.commit()
            session.rollback()

            user = User(email="foreign-key@example.com", password_hash="hash")
            session.add(user)
            session.commit()
            session.add(UserPlatformRole(user_id=user.id, role_key="unknown-role"))
            with self.assertRaises(IntegrityError):
                session.commit()
            session.rollback()

    def test_musician_profile_user_foreign_key_is_enforced_by_postgres(self) -> None:
        with self.engine.connect() as connection:
            transaction = connection.begin()
            with self.assertRaises(IntegrityError):
                connection.execute(
                    text(
                        "INSERT INTO musician_profiles "
                        "(display_name, city, genres, instruments, years_experience, "
                        "band_status, user_id) VALUES "
                        "('Orphan', 'Pune', 'Jazz', 'Guitar', 1, 'solo', :user_id)"
                    ),
                    {"user_id": str(uuid4())},
                )
            transaction.rollback()

    def test_existing_musician_profile_survives_nullable_user_link_migration(self) -> None:
        with self.engine.connect() as connection:
            profile = connection.execute(
                text(
                    "SELECT display_name, city, user_id FROM musician_profiles "
                    "WHERE display_name = 'Existing Profile'"
                )
            ).one()

        self.assertEqual(profile.display_name, "Existing Profile")
        self.assertEqual(profile.city, "Pune")
        self.assertIsNone(profile.user_id)

    def test_upgrade_head_again_is_idempotent(self) -> None:
        self._run_migration("head")
        with self.engine.connect() as connection:
            revision = connection.execute(
                text("SELECT version_num FROM alembic_version")
            ).scalar_one()

        self.assertEqual(revision, "a6d3f7c4e921")

    def test_schema_cleanup_runs_when_setup_fails(self) -> None:
        schema_name_holder: list[str] = []
        admin_engine = create_engine(
            _validated_test_database_url(os.environ.get(TEST_DATABASE_ENV))
        )

        class FailingSetupProbe(unittest.TestCase):
            @classmethod
            def setUpClass(probe_cls) -> None:
                probe_cls.addClassCleanup(admin_engine.dispose)
                schema_name_holder.append(
                    _create_test_schema_and_register_cleanup(probe_cls, admin_engine)
                )
                raise RuntimeError("intentional setup failure for cleanup validation")

            def test_unreachable(self) -> None:
                self.fail("setUpClass should prevent test execution")

        result = unittest.TestResult()
        suite = unittest.defaultTestLoader.loadTestsFromTestCase(FailingSetupProbe)
        suite.run(result)

        self.assertEqual(len(result.errors), 1)
        schema_name = schema_name_holder[0]
        with self.admin_engine.connect() as connection:
            remaining = connection.execute(
                text("SELECT 1 FROM pg_namespace WHERE nspname = :schema"),
                {"schema": schema_name},
            ).scalar_one_or_none()

        self.assertIsNone(remaining)


if __name__ == "__main__":
    unittest.main()
